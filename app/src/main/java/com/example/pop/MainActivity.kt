private fun rollRarity(): Rarity {
    val n = Random.nextInt(100)
    return when { n < 65 -> Rarity.COMMON; n < 88 -> Rarity.UNCOMMON; n < 97 -> Rarity.RARE; n < 99 -> Rarity.EPIC; else -> Rarity.LEGENDARY }
}
private fun fakeNumber(rarity: Rarity): String {
    val digits = when (rarity) {
        Rarity.COMMON -> (1..10).joinToString("") { Random.nextInt(0, 10).toString() }
        Rarity.UNCOMMON -> { val d = Random.nextInt(0, 10); "${Random.nextInt(0,10)}$d$d${Random.nextInt(0,10)}${Random.nextInt(0,10)}${Random.nextInt(0,10)}${Random.nextInt(0,10)}" }
        Rarity.RARE -> { val d = Random.nextInt(0,10); "${Random.nextInt(0,10)}$d$d$d${Random.nextInt(0,10)}${Random.nextInt(0,10)}" }
        Rarity.EPIC -> { val d = Random.nextInt(0,10); "${Random.nextInt(0,10)}$d$d$d$d${Random.nextInt(0,10)}" }
        Rarity.LEGENDARY -> { val d = Random.nextInt(0,10); "$d$d$d$d$d$d$d" }
    }
    return "+000 ${digits.take(3)} ${digits.drop(3).take(3)} ${digits.drop(6)}"
}
private fun loadStorage(raw: String): List<FoundNumber> = raw.split("~").mapNotNull { entry -> val parts = entry.split("|"); if (parts.size == 2) runCatching { FoundNumber(parts[0], Rarity.valueOf(parts[1])) }.getOrNull() else null }
