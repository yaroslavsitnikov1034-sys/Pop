@Composable private fun StorageScreen(storage: List<FoundNumber>, capacity: Int, panel: Color, text: Color, onSell: (FoundNumber) -> Unit, onSellAll: () -> Unit) {
    Column(Modifier.fillMaxSize().padding(horizontal = 16.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) { Text("${storage.size} / $capacity мест", color = text, fontWeight = FontWeight.Bold, modifier = Modifier.weight(1f)); TextButton(onClick = onSellAll, enabled = storage.isNotEmpty()) { Text("Продать всё") } }
