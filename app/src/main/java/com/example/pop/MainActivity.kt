@Composable
private fun PhoneCollectorApp() {
    val context = LocalContext.current
    val prefs = remember { context.getSharedPreferences("phone_collector_save", Context.MODE_PRIVATE) }
    var coins by remember { mutableIntStateOf(prefs.getInt("coins", 0)) }
    var generated by remember { mutableIntStateOf(prefs.getInt("generated", 0)) }
    var sold by remember { mutableIntStateOf(prefs.getInt("sold", 0)) }
    var autoLevel by remember { mutableIntStateOf(prefs.getInt("autoLevel", 0)) }
    var storageLevel by remember { mutableIntStateOf(prefs.getInt("storageLevel", 0)) }
    var storage by remember { mutableStateOf(loadStorage(prefs.getString("storage", "") ?: "")) }
    var current by remember { mutableStateOf(FoundNumber("+000 000 000 000", Rarity.COMMON)) }
    var tab by remember { mutableStateOf(Tab.GENERATOR) }
    var autoEnabled by remember { mutableStateOf(prefs.getBoolean("autoEnabled", false)) }
    var darkTheme by remember { mutableStateOf(prefs.getBoolean("darkTheme", true)) }
    var soundEnabled by remember { mutableStateOf(prefs.getBoolean("sound", true)) }
    var vibrationEnabled by remember { mutableStateOf(prefs.getBoolean("vibration", true)) }
    var autoSell by remember { mutableStateOf(prefs.getBoolean("autoSell", false)) }
    var sellCommon by remember { mutableStateOf(prefs.getBoolean("sellCommon", true)) }
    var sellUncommon by remember { mutableStateOf(prefs.getBoolean("sellUncommon", true)) }
    var sellRare by remember { mutableStateOf(prefs.getBoolean("sellRare", false)) }
    var sellEpic by remember { mutableStateOf(prefs.getBoolean("sellEpic", false)) }
    var sellLegendary by remember { mutableStateOf(prefs.getBoolean("sellLegendary", false)) }
    var notice by remember { mutableStateOf("") }
    val capacity = 20 + storageLevel * 10
    val totalByRarity = remember(generated, storage) { Rarity.values().associateWith { r -> storage.count { it.rarity == r } } }

    fun persist() {
        prefs.edit().putInt("coins", coins).putInt("generated", generated).putInt("sold", sold)
            .putInt("autoLevel", autoLevel).putInt("storageLevel", storageLevel)
            .putString("storage", storage.joinToString("~") { "${it.value}|${it.rarity.name}" })
            .putBoolean("autoEnabled", autoEnabled).putBoolean("darkTheme", darkTheme)
            .putBoolean("sound", soundEnabled).putBoolean("vibration", vibrationEnabled)
            .putBoolean("autoSell", autoSell).putBoolean("sellCommon", sellCommon)
            .putBoolean("sellUncommon", sellUncommon).putBoolean("sellRare", sellRare)
            .putBoolean("sellEpic", sellEpic).putBoolean("sellLegendary", sellLegendary).apply()
    }
    fun shouldSell(r: Rarity) = autoSell && when (r) {
        Rarity.COMMON -> sellCommon; Rarity.UNCOMMON -> sellUncommon; Rarity.RARE -> sellRare
        Rarity.EPIC -> sellEpic; Rarity.LEGENDARY -> sellLegendary
    }
    fun generate() {
        val rarity = rollRarity()
        val number = FoundNumber(fakeNumber(rarity), rarity)
        generated++
        current = number
        if (shouldSell(rarity)) { coins += rarity.payout; sold++; notice = "Автопродажа: +${rarity.payout} монет" }
        else if (storage.size < capacity) { storage = listOf(number) + storage; notice = "Найден номер: ${rarity.title}" }
        else { notice = "Хранилище заполнено! Улучши вместимость или продай номера." }
        persist()
    }

    LaunchedEffect(autoEnabled, autoLevel, tab) {
        while (true) {
            delay((2200L - autoLevel * 250L).coerceAtLeast(350L))
            if (autoEnabled && autoLevel > 0) generate()
        }
    }

    val screenBg = if (darkTheme) Bg else Color(0xFFF3F5FB)
    val textColor = if (darkTheme) Color.White else Color(0xFF182039)
    val panelColor = if (darkTheme) Panel else Color.White
    Surface(modifier = Modifier.fillMaxSize(), color = screenBg) {
        Column(Modifier.fillMaxSize()) {
            Row(Modifier.fillMaxWidth().padding(horizontal = 20.dp, vertical = 14.dp), verticalAlignment = Alignment.CenterVertically) {
                Column(Modifier.weight(1f)) {
                    Text("PHONE COLLECTOR", color = Accent, fontSize = 12.sp, fontWeight = FontWeight.Bold, letterSpacing = 2.sp)
                    Text(tab.label, color = textColor, fontSize = 25.sp, fontWeight = FontWeight.ExtraBold)
                }
                Surface(color = panelColor, shape = RoundedCornerShape(16.dp)) {
                    Row(Modifier.padding(horizontal = 13.dp, vertical = 10.dp), verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Default.MonetizationOn, null, tint = Color(0xFFFFC857), modifier = Modifier.size(20.dp))
                        Spacer(Modifier.width(6.dp)); Text("$coins", color = textColor, fontWeight = FontWeight.Bold)
                    }
                }
            }
            Box(Modifier.weight(1f).fillMaxWidth()) {
                when (tab) {
                    Tab.GENERATOR -> GeneratorScreen(current, generated, autoEnabled, autoLevel, notice, panelColor, textColor, onTap = { generate() }, onAuto = { autoEnabled = it; persist() })
                    Tab.STORAGE -> StorageScreen(storage, capacity, panelColor, textColor, onSell = { item -> storage = storage.filterNot { it.id == item.id }; coins += item.rarity.payout; sold++; notice = "Продано за ${item.rarity.payout} монет"; persist() }, onSellAll = { coins += storage.sumOf { it.rarity.payout }; sold += storage.size; storage = emptyList(); notice = "Хранилище продано"; persist() })
                    Tab.UPGRADES -> UpgradeScreen(coins, autoLevel, storageLevel, panelColor, textColor,
                        onAuto = { cost -> if (coins >= cost && autoLevel < 8) { coins -= cost; autoLevel++; persist() } },
                        onStorage = { cost -> if (coins >= cost && storageLevel < 20) { coins -= cost; storageLevel++; persist() } })
                    Tab.STATS -> StatsScreen(generated, sold, coins, storage, totalByRarity, panelColor, textColor)
                    Tab.SETTINGS -> SettingsScreen(darkTheme, soundEnabled, vibrationEnabled, autoSell, sellCommon, sellUncommon, sellRare, sellEpic, sellLegendary, panelColor, textColor,
                        { darkTheme = it; persist() }, { soundEnabled = it; persist() }, { vibrationEnabled = it; persist() }, { autoSell = it; persist() },
                        { sellCommon = it; persist() }, { sellUncommon = it; persist() }, { sellRare = it; persist() }, { sellEpic = it; persist() }, { sellLegendary = it; persist() },
                        { prefs.edit().clear().apply(); coins = 0; generated = 0; sold = 0; autoLevel = 0; storageLevel = 0; storage = emptyList(); autoEnabled = false; autoSell = false; notice = "Прогресс сброшен" })
                }
            }
            NavigationBar(containerColor = panelColor) {
                Tab.values().forEach { item ->
                    NavigationBarItem(selected = tab == item, onClick = { tab = item }, icon = { Icon(when(item) { Tab.GENERATOR -> Icons.Default.TouchApp; Tab.STORAGE -> Icons.Default.Inventory2; Tab.UPGRADES -> Icons.Default.Upgrade; Tab.STATS -> Icons.Default.BarChart; Tab.SETTINGS -> Icons.Default.Settings }, contentDescription = item.label) }, label = { Text(item.label, fontSize = 9.sp) })
                }
            }
        }
    }
}

