        else LazyColumn(verticalArrangement = Arrangement.spacedBy(8.dp), contentPadding = PaddingValues(bottom = 12.dp)) {
            items(storage, key = { it.id }) { item -> Surface(color = panel, shape = RoundedCornerShape(16.dp)) { Row(Modifier.fillMaxWidth().padding(14.dp), verticalAlignment = Alignment.CenterVertically) { Column(Modifier.weight(1f)) { Text(item.value, color = text, fontWeight = FontWeight.Bold); Text(item.rarity.title, color = item.rarity.color, fontSize = 12.sp) }; Text("${item.rarity.payout} 🪙", color = Mint); IconButton(onClick = { onSell(item) }) { Icon(Icons.Default.Sell, "Продать", tint = Accent) } } } }
        }
    }
}

